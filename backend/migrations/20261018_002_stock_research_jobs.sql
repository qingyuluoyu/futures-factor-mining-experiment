CREATE TABLE stock_research_jobs (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    trading_mode VARCHAR(16) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    title VARCHAR(80) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    step VARCHAR(32) NOT NULL DEFAULT 'queued',
    progress INTEGER NOT NULL DEFAULT 0,
    request_id VARCHAR(32) NOT NULL,
    idempotency_key UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    params_json JSONB NOT NULL,
    method_version VARCHAR(64) NOT NULL,
    workflow_version VARCHAR(40) NOT NULL,
    data_version VARCHAR(64),
    data_manifest JSONB NOT NULL DEFAULT '{}'::jsonb,
    result_json JSONB,
    result_bytes INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 0,
    worker_token UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    deadline_at TIMESTAMPTZ,
    lease_expires_at TIMESTAMPTZ,
    error_code VARCHAR(64),
    error_message VARCHAR(500),
    error_status INTEGER,
    CONSTRAINT uq_stock_research_job_key UNIQUE (user_id, trading_mode, idempotency_key),
    CONSTRAINT ck_stock_research_job_mode CHECK (trading_mode = 'live' OR trading_mode = 'virtual'),
    CONSTRAINT ck_stock_research_job_kind CHECK (kind = 'analysis' OR kind = 'backtest'),
    CONSTRAINT ck_stock_research_job_status CHECK (status = 'pending' OR status = 'running' OR status = 'completed' OR status = 'failed' OR status = 'cancelled' OR status = 'expired'),
    CONSTRAINT ck_stock_research_job_progress CHECK (progress >= 0 AND progress <= 100),
    CONSTRAINT ck_stock_research_job_attempts CHECK (attempts >= 0 AND attempts <= 1),
    CONSTRAINT ck_stock_research_job_result_bytes CHECK (result_bytes >= 0 AND result_bytes <= 8388608),
    CONSTRAINT ck_stock_research_job_result CHECK ((status = 'completed' AND result_json IS NOT NULL AND data_version IS NOT NULL AND finished_at IS NOT NULL) OR (status <> 'completed' AND result_json IS NULL)),
    CONSTRAINT ck_stock_research_job_running CHECK (status <> 'running' OR (worker_token IS NOT NULL AND started_at IS NOT NULL AND deadline_at IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CONSTRAINT ck_stock_research_job_finished CHECK (status = 'pending' OR status = 'running' OR finished_at IS NOT NULL)
);

CREATE INDEX ix_stock_research_job_user_mode_created ON stock_research_jobs (user_id, trading_mode, created_at, id);
CREATE INDEX ix_stock_research_job_status_created ON stock_research_jobs (status, created_at);
CREATE INDEX ix_stock_research_job_status_lease ON stock_research_jobs (status, lease_expires_at);
