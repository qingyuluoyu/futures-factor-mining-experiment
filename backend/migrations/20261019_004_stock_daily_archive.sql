CREATE TABLE stock_daily_archive_batches (
    id UUID PRIMARY KEY,
    version CHAR(64) NOT NULL UNIQUE,
    source_batch_id UUID NOT NULL,
    source_data_version CHAR(64) NOT NULL,
    method_version VARCHAR(64) NOT NULL,
    trade_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    source_collected_at TIMESTAMPTZ NOT NULL,
    archived_at TIMESTAMPTZ NOT NULL,
    row_count INTEGER NOT NULL,
    expected_count INTEGER NOT NULL,
    missing_count INTEGER NOT NULL,
    unknown_count INTEGER NOT NULL,
    source_metadata JSONB NOT NULL,
    CONSTRAINT uq_stock_daily_archive_source_method UNIQUE (source_batch_id, method_version),
    CONSTRAINT uq_stock_daily_archive_id_date UNIQUE (id, trade_date),
    CONSTRAINT ck_stock_daily_archive_status CHECK (status = 'completed'),
    CONSTRAINT ck_stock_daily_archive_rows CHECK (row_count >= 1 AND row_count <= 10000),
    CONSTRAINT ck_stock_daily_archive_expected CHECK (expected_count >= 1 AND expected_count <= 10000),
    CONSTRAINT ck_stock_daily_archive_missing CHECK (missing_count >= 0 AND missing_count <= 10000),
    CONSTRAINT ck_stock_daily_archive_unknown CHECK (unknown_count >= 0 AND unknown_count <= 10000),
    CONSTRAINT ck_stock_daily_archive_coverage CHECK (row_count + missing_count = expected_count),
    CONSTRAINT ck_stock_daily_archive_times CHECK (source_collected_at <= archived_at)
);
CREATE INDEX ix_stock_daily_archive_date ON stock_daily_archive_batches (trade_date, archived_at);
CREATE TABLE stock_daily_observations (
    batch_id UUID NOT NULL,
    instrument_id VARCHAR(16) NOT NULL,
    code CHAR(6) NOT NULL,
    exchange VARCHAR(8) NOT NULL,
    trade_date DATE NOT NULL,
    currency CHAR(3) NOT NULL,
    price_adjustment VARCHAR(8) NOT NULL,
    volume_unit VARCHAR(24) NOT NULL,
    amount_unit VARCHAR(8) NOT NULL,
    open NUMERIC(38, 18) NOT NULL,
    high NUMERIC(38, 18) NOT NULL,
    low NUMERIC(38, 18) NOT NULL,
    close NUMERIC(38, 18) NOT NULL,
    pre_close NUMERIC(38, 18) NOT NULL,
    volume NUMERIC(38, 18) NOT NULL,
    amount NUMERIC(38, 18) NOT NULL,
    PRIMARY KEY (batch_id, instrument_id),
    CONSTRAINT uq_stock_daily_observation_batch_code UNIQUE (batch_id, code),
    CONSTRAINT fk_stock_daily_observation_batch_date FOREIGN KEY (batch_id, trade_date) REFERENCES stock_daily_archive_batches (id, trade_date) ON DELETE RESTRICT,
    CONSTRAINT ck_stock_daily_units CHECK (currency = 'CNY' AND price_adjustment = 'none' AND volume_unit = 'lot_100_shares' AND amount_unit = 'CNY'),
    CONSTRAINT ck_stock_daily_identity CHECK (code ~ '^[0-9]{6}$' AND ((exchange = 'SSE' AND code ~ '^6' AND instrument_id = code || '.SH') OR (exchange = 'SZSE' AND code ~ '^[03]' AND instrument_id = code || '.SZ') OR (exchange = 'BSE' AND code ~ '^[489]' AND instrument_id = code || '.BJ'))),
    CONSTRAINT ck_stock_daily_open CHECK (open > 0 AND open < 100000000000000000000),
    CONSTRAINT ck_stock_daily_high CHECK (high > 0 AND high < 100000000000000000000),
    CONSTRAINT ck_stock_daily_low CHECK (low > 0 AND low < 100000000000000000000),
    CONSTRAINT ck_stock_daily_close CHECK (close > 0 AND close < 100000000000000000000),
    CONSTRAINT ck_stock_daily_pre_close CHECK (pre_close > 0 AND pre_close < 100000000000000000000),
    CONSTRAINT ck_stock_daily_volume CHECK (volume >= 0 AND volume < 100000000000000000000),
    CONSTRAINT ck_stock_daily_amount CHECK (amount >= 0 AND amount < 100000000000000000000),
    CONSTRAINT ck_stock_daily_ohlc CHECK (low <= open AND low <= close AND open <= high AND close <= high)
);
CREATE INDEX ix_stock_daily_observation_code_date ON stock_daily_observations (code, trade_date);
