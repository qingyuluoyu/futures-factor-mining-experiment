def extract_base_symbol(contract: str) -> str:
    """从合约代码中提取基础品种代码（如 rb2610 → rb）"""
    base = []
    for ch in contract.lower():
        if ch.isalpha():
            base.append(ch)
        else:
            break
    return "".join(base)


def get_primary_keyword(symbol: str) -> str | None:
    """获取品种的主搜索关键词（取第一个关键词，通常是最精确的）"""
    keywords = CONTRACT_KEYWORDS.get(symbol.lower())
    return keywords[0] if keywords else None


def find_matching_symbols(title: str) -> list[str]:
    """从新闻标题中匹配关联品种代码"""
    matched: list[str] = []
    for symbol, keywords in CONTRACT_KEYWORDS.items():
        for kw in keywords:
            if kw in title:
                matched.append(symbol)
                break
    return matched
